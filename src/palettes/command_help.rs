//! Longer help for each tmux command — what it does, an example, and what each
//! of its flags means — for the command prompt's details strip and argument
//! rows. tmux publishes none of this in a form a program can read
//! (`list-commands` gives only the usage line), so it is written out here from
//! the man page and checked against tmux's source.
//!
//! It covers every flag of every command in tmux 3.4 and in tmux's development
//! version as of October 2026. A flag from some other version falls back to the
//! command prompt's generic descriptions, and an unknown command to its usage.

pub struct CommandHelp {
    pub name: &'static str,
    /// One or two sentences: what the command does, and what a newcomer most
    /// needs to know about it.
    pub about: &'static str,
    /// A realistic command line, valid in tmux 3.4.
    pub example: &'static str,
    /// What each flag means for this command, by flag letter.
    pub flags: &'static [(char, &'static str)],
    /// Positional arguments this command gives a specific meaning.
    pub args: &'static [(&'static str, &'static str)],
}

impl CommandHelp {
    pub fn flag(&self, letter: char) -> Option<&'static str> {
        self.flags
            .iter()
            .find(|(l, _)| *l == letter)
            .map(|(_, d)| *d)
    }

    pub fn arg(&self, name: &str) -> Option<&'static str> {
        self.args.iter().find(|(a, _)| *a == name).map(|(_, d)| *d)
    }
}

/// `HELP` is sorted by name, so this binary-searches.
pub fn help_for(name: &str) -> Option<&'static CommandHelp> {
    HELP.binary_search_by_key(&name, |h| h.name)
        .ok()
        .map(|i| &HELP[i])
}

